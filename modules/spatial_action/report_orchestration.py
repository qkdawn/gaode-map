    @staticmethod
    def _execution_context(
        metric_plan_entries: list[dict[str, Any]],
        metric_attempts: list[dict[str, Any]],
        evidence_nodes: list[dict[str, Any]],
    ) -> tuple[dict[str, MetricPlanEntry], set[str]]:
        entries = {
            entry.plan_entry_id: entry
            for entry in (MetricPlanEntry.model_validate(item) for item in metric_plan_entries)
        }
        evidence_ids = {str(node.get("id") or "") for node in evidence_nodes}
        for attempt in metric_attempts:
            entry = entries.get(str(attempt.get("plan_entry_id") or ""))
            if entry is None:
                raise ValueError(f"MetricAttempt references unknown plan entry: {attempt.get('plan_entry_id')}")
            status = str(attempt.get("execution_status") or "")
            if status == "succeeded":
                for evidence_id in attempt.get("evidence_node_ids") or []:
                    if evidence_id not in evidence_ids:
                        raise ValueError(f"MetricAttempt references unknown EvidenceNode: {evidence_id}")
        return entries, evidence_ids

    async def _lock_publication_blueprint(
        self,
        *,
        blueprint: ProjectAnalysisBlueprint,
        completeness_review: BlueprintCompletenessReview,
        metric_plan_entries: list[dict[str, Any]],
        metric_attempts: list[dict[str, Any]],
        evidence_attempts: list[dict[str, Any]],
        evidence_gates: list[dict[str, Any]],
        evidence_nodes: list[dict[str, Any]],
        visual_catalog: ReportVisualCatalog,
        diagnostics: list[str],
    ) -> tuple[EvidenceReadinessReview, PublicationBlueprint]:
        evidence_snapshot_hash = visual_catalog.evidence_snapshot_hash
        successful_evidence_ids = {str(item.get("id") or "") for item in evidence_nodes}
        blocked_entry_ids = {
            str(item.get("plan_ref_id") or "")
            for item in evidence_attempts
            if str(item.get("execution_status") or "") in {"blocked", "failed", "registered_gap"}
        }
        blocked_by_question: dict[str, set[str]] = {}
        for item in evidence_attempts:
            if str(item.get("execution_status") or "") in {"blocked", "failed", "registered_gap"}:
                blocked_by_question.setdefault(str(item.get("decision_question_id") or ""), set()).add(
                    str(item.get("plan_ref_id") or "")
                )
        visual_ids = {item.visual_id for item in visual_catalog.candidates}
        question_ids = {item.question_id for item in blueprint.decision_questions}

        def validate(raw: dict[str, Any]) -> tuple[EvidenceReadinessReview, PublicationBlueprint]:
            payload = EvidenceReadinessPayload.model_validate(raw)
            review = payload.review
            publication = payload.publication_blueprint
            if completeness_review.decision != "accepted":
                raise ValueError("publication blueprint cannot lock from an unaccepted analysis blueprint")
            for item in (review, publication):
                if item.run_id != blueprint.run_id:
                    raise ValueError("evidence readiness artifact references the wrong run")
                if item.blueprint_id != blueprint.blueprint_id or item.blueprint_hash != blueprint.blueprint_hash:
                    raise ValueError("evidence readiness artifact references the wrong blueprint")
                if item.evidence_snapshot_hash != evidence_snapshot_hash:
                    raise ValueError("evidence readiness artifact references the wrong evidence snapshot")
            if {item.decision_question_id for item in review.question_readiness} != question_ids:
                raise ValueError("EvidenceReadinessReview must cover every DecisionQuestion")
            for item in review.question_readiness:
                expected_blocked = blocked_by_question.get(item.decision_question_id, set())
                if set(item.blocked_plan_entry_ids) != expected_blocked:
                    raise ValueError("EvidenceReadinessReview must retain every blocked or gap EvidencePlan item")
                if expected_blocked and not item.succeeded_evidence_ids and item.status not in {"gap_bound", "not_reportable"}:
                    raise ValueError("a question with only blocked or gap evidence must be gap_bound or not_reportable")
            owned = {
                question_id
                for assignment in publication.chapter_assignments
                for question_id in assignment.decision_question_ids
            }
            if owned != question_ids:
                raise ValueError("PublicationBlueprint must retain every DecisionQuestion")
            for assignment in publication.chapter_assignments:
                access = assignment.evidence_access
                if not (set(access.primary_refs) | set(access.shared_refs) | set(access.forbidden_refs)) <= successful_evidence_ids:
                    raise ValueError("ChapterAssignment evidence_access references unknown evidence")
                if not set(access.gap_refs) <= blocked_entry_ids:
                    raise ValueError("ChapterAssignment gap_refs must reference blocked or failed plan entries")
                if not set(access.visual_refs) <= visual_ids:
                    raise ValueError("ChapterAssignment visual_refs reference unknown visual candidates")
                assignment.assignment_hash = ""
                assignment.assignment_hash = _digest(assignment.model_dump(mode="json", exclude={"assignment_hash"}))
            if {
                plan_ref
                for assignment in publication.chapter_assignments
                for plan_ref in assignment.evidence_access.gap_refs
            } != blocked_entry_ids:
                raise ValueError("PublicationBlueprint must authorize every blocked or gap plan item to its owning chapter")
            publication.assignment_bundle_hash = ""
            publication.assignment_bundle_hash = _digest(
                publication.model_dump(mode="json", exclude={"assignment_bundle_hash"})
            )
            return review, publication

        review, publication = await self._validated_chat(
            system_prompt=(
                "你是项目主分析师的 EvidenceReadinessReview 角色。问题与 EvidencePlan 已经锁定，不能因执行失败而删除问题。"
                "检查每个问题的成功证据、blocked/failed 条目和图表可用性，再锁定实际出版结构。"
                "可合并或重排初步章节，但每个 DecisionQuestion 必须进入一个主责章节；证据可通过 primary_refs/shared_refs 授权给多个章节。"
                "gap_refs 只能填 blocked/failed plan_entry_id，visual_refs 只能填给定 visual_id，forbidden_refs 明确禁止越权引用。"
                "如果必须由用户补文件或作范围/方案选择，decision=needs_user_input；系统或关键证据链无法出版则 publication_blocked；"
                "其他缺口应降级为 gap_bound/conditional 并继续；not_reportable 问题不得静默消失。只返回 {review,publication_blueprint} JSON。"
            ),
            user_payload={
                "project_analysis_blueprint": blueprint.model_dump(mode="json"),
                "blueprint_completeness_review": completeness_review.model_dump(mode="json"),
                "metric_plan_entries": metric_plan_entries,
                "metric_attempts": metric_attempts,
                "evidence_attempts": evidence_attempts,
                "evidence_gates": evidence_gates,
                "evidence_nodes": evidence_nodes,
                "report_visual_catalog": visual_catalog.model_dump(mode="json"),
                "diagnostics": diagnostics,
            },
            phase="spatial-evidence-readiness",
            title="主分析师锁定证据就绪度与出版章节",
            reasoning_id="spatial-main-evidence-readiness",
            validator=validate,
        )
        if review.decision == "needs_user_input":
            raise OrchestrationError(
                review.reason,
                run_status="waiting_for_user",
                partial_artifacts={
                    "evidence_readiness_review": review.model_dump(mode="json"),
                    "publication_blueprint": publication.model_dump(mode="json"),
                },
            )
        if review.decision == "publication_blocked":
            raise OrchestrationError(
                review.reason,
                run_status="publication_blocked",
                partial_artifacts={
                    "evidence_readiness_review": review.model_dump(mode="json"),
                    "publication_blueprint": publication.model_dump(mode="json"),
                },
            )
        return review, publication

    @staticmethod
    def _validate_chapter(
        chapter: AnalystChapterPackage,
        *,
        assignment: ChapterAssignment,
        plan_ref_questions: dict[str, str],
        successful_evidence_ids: set[str],
        blocked_attempts: dict[str, dict[str, Any]],
        object_ids: set[str],
        visual_by_id: dict[str, ReportVisualCandidate],
        evidence_snapshot_hash: str,
        run_id: str,
        expected_revision: int,
    ) -> AnalystChapterPackage:
        if chapter.run_id != run_id:
            raise ValueError("AnalystChapterPackage returned the wrong run_id")
        if chapter.chapter_id != assignment.chapter_id or chapter.analyst_role != assignment.analyst_role:
            raise ValueError("AnalystChapterPackage returned the wrong chapter identity or analyst role")
        revision_match = re.search(r"(?:^|[:._-])v(\d+)$", chapter.chapter_version_id, flags=re.IGNORECASE)
        if revision_match is None or int(revision_match.group(1)) != expected_revision:
            raise ValueError(f"AnalystChapterPackage must use chapter revision v{expected_revision}")
        if set(chapter.decision_question_ids) != set(assignment.decision_question_ids):
            raise ValueError("AnalystChapterPackage must cover exactly its assigned DecisionQuestions")
        brief_by_id = {item.subsection_id: item for item in assignment.subsection_briefs}
        if {item.subsection_id for item in chapter.subsections} != set(brief_by_id):
            raise ValueError("AnalystChapterPackage must return every assigned subsection exactly once")
        finding_by_id = {item.finding_id: item for item in chapter.finding_packets}
        gap_by_id = {item.gap_id: item for item in chapter.evidence_gaps}
        allowed_questions = set(assignment.decision_question_ids)
        allowed_evidence = set(assignment.evidence_access.primary_refs) | set(assignment.evidence_access.shared_refs)
        if not allowed_evidence <= successful_evidence_ids:
            raise ValueError("ChapterAssignment authorizes unknown or non-success evidence")
        if allowed_evidence & set(assignment.evidence_access.forbidden_refs):
            raise ValueError("ChapterAssignment authorizes forbidden evidence")
        allowed_gap_entries = set(assignment.evidence_access.gap_refs)
        allowed_visuals = set(assignment.evidence_access.visual_refs)
        used_visuals: set[str] = set()
        for finding in chapter.finding_packets:
            if finding.decision_question_id not in allowed_questions:
                raise ValueError("FindingPacket belongs to another chapter")
            if not set(finding.evidence_ids) <= allowed_evidence:
                raise ValueError("FindingPacket references evidence outside the chapter assignment")
        for gap in chapter.evidence_gaps:
            if gap.decision_question_id not in allowed_questions:
                raise ValueError("EvidenceGap belongs to another chapter")
            for entry_id in gap.blocked_plan_entry_ids:
                if (
                    entry_id not in blocked_attempts
                    or plan_ref_questions.get(entry_id) != gap.decision_question_id
                ):
                    raise ValueError("EvidenceGap references a non-blocked or cross-question EvidencePlan item")
                if entry_id not in allowed_gap_entries:
                    raise ValueError("EvidenceGap references a blocked plan item not authorized for the chapter")
        for option in chapter.option_comparisons:
            if not set(option.evidence_ids) <= allowed_evidence:
                raise ValueError("OptionComparison references evidence outside the chapter assignment")
        for subsection in chapter.subsections:
            brief = brief_by_id[subsection.subsection_id]
            if set(subsection.decision_question_ids) != set(brief.decision_question_ids):
                raise ValueError("subsection DecisionQuestions do not match its blueprint brief")
            if not set(subsection.evidence_ids) <= allowed_evidence:
                raise ValueError("subsection references evidence outside the chapter assignment")
            citations = set(CITATION_TOKEN.findall(subsection.body))
            if not citations <= set(subsection.evidence_ids):
                raise ValueError("subsection body cites evidence not declared by the subsection")
            if not set(subsection.object_ids) <= object_ids:
                raise ValueError("subsection references unknown spatial objects")
            if not set(subsection.finding_ids) <= set(finding_by_id):
                raise ValueError("subsection references unknown FindingPackets")
            if not set(subsection.evidence_gap_ids) <= set(gap_by_id):
                raise ValueError("subsection references unknown EvidenceGaps")
            argument_ids = [item.argument_id for item in subsection.argument_units]
            if len(argument_ids) != len(set(argument_ids)):
                raise ValueError("subsection ArgumentUnit ids must be unique")
            for argument in subsection.argument_units:
                if not set(argument.evidence_refs) <= allowed_evidence:
                    raise ValueError("ArgumentUnit references evidence outside the chapter authorization")
                if not set(argument.evidence_gap_refs) <= set(gap_by_id):
                    raise ValueError("ArgumentUnit references unknown EvidenceGaps")
            for block in subsection.structured_blocks:
                if not set(block.evidence_ids) <= allowed_evidence:
                    raise ValueError("StructuredBlock references evidence outside the chapter assignment")
                if not set(block.evidence_gap_ids) <= set(gap_by_id):
                    raise ValueError("StructuredBlock references unknown EvidenceGaps")
            for visual_ref in subsection.visual_refs:
                used_visuals.add(visual_ref.visual_id)
                visual = visual_by_id.get(visual_ref.visual_id)
                if visual is None:
                    raise ValueError("subsection references an unknown visual candidate")
                if visual_ref.visual_id not in allowed_visuals:
                    raise ValueError("visual candidate is not authorized for the chapter")
                if not set(visual.object_ids) <= object_ids:
                    raise ValueError("visual candidate references unknown spatial objects")
        if used_visuals != allowed_visuals:
            raise ValueError("AnalystChapterPackage must place and interpret every assigned visual")
        chapter.assignment_hash = assignment.assignment_hash
        chapter.evidence_snapshot_hash = evidence_snapshot_hash
        chapter.content_hash = ""
        chapter.content_hash = _digest(chapter.model_dump(mode="json", exclude={"content_hash"}))
        return chapter

    @staticmethod
    def _validate_review(
        review: LegacyEditorialReview,
        *,
        chapters: list[AnalystChapterPackage],
        successful_evidence_ids: set[str],
    ) -> LegacyEditorialReview:
        chapter_ids = {item.chapter_id for item in chapters}
        if review.run_id != chapters[0].run_id:
            raise ValueError("EditorialReview references the wrong run")
        claim_ids = {
            argument.argument_id
            for chapter in chapters
            for subsection in chapter.subsections
            for argument in subsection.argument_units
        }
        if {item.chapter_id for item in review.chapter_decisions} != chapter_ids:
            raise ValueError("EditorialReview must decide every chapter")
        if set(review.chapter_order) != chapter_ids or len(review.chapter_order) != len(chapter_ids):
            raise ValueError("EditorialReview chapter_order must contain every chapter exactly once")
        for conflict in review.cross_chapter_conflicts:
            if not set(conflict.chapter_ids) <= chapter_ids or not set(conflict.repair_chapter_ids) <= chapter_ids:
                raise ValueError("EditorialConflict references unknown chapters")
            if not set(conflict.evidence_ids) <= successful_evidence_ids:
                raise ValueError("EditorialConflict references non-success evidence")
            if not set(conflict.claim_ids) <= claim_ids:
                raise ValueError("EditorialConflict may only adjudicate accepted chapter claims")
        unresolved_chapter_ids = {item.chapter_id for item in chapters if item.unresolved_tensions}
        conflict_chapter_ids = {
            chapter_id for conflict in review.cross_chapter_conflicts for chapter_id in conflict.chapter_ids
        }
        revise_chapter_ids = {
            item.chapter_id for item in review.chapter_decisions if item.status == "revise"
        }
        if not unresolved_chapter_ids <= conflict_chapter_ids | revise_chapter_ids:
            raise ValueError("EditorialReview must explicitly resolve or return every declared chapter tension")
        if any(item.before_chapter_id not in chapter_ids for item in review.transitions):
            raise ValueError("EditorialReview transition references an unknown chapter")
        statements = [review.executive_judgment, *review.integrated_recommendations]
        statements.extend(SynthesisStatement(text=item.text, claim_ids=item.claim_ids) for item in review.transitions)
        if any(not set(item.claim_ids) <= claim_ids for item in statements):
            raise ValueError("EditorialReview synthesis may only reference accepted chapter claims")
        return review

    async def _editorial_review(
        self,
        *,
        blueprint: ProjectAnalysisBlueprint,
        chapters: list[AnalystChapterPackage],
        evidence_nodes: list[dict[str, Any]],
        diagnostics: list[str],
        successful_evidence_ids: set[str],
        final_pass: bool,
    ) -> LegacyEditorialReview:
        def validate(raw: dict[str, Any]) -> LegacyEditorialReview:
            review = self._validate_review(
                LegacyEditorialReview.model_validate(raw),
                chapters=chapters,
                successful_evidence_ids=successful_evidence_ids,
            )
            if final_pass and review.publication_decision != "ready":
                raise ValueError("final editorial pass must accept every repaired chapter")
            return review

        return await self._validated_chat(
            system_prompt=(
                "你是项目主分析师的总编角色。逐章阅读全文，检查证据边界、术语、重复、跨章冲突、实施顺序和论证深度。"
                "你不得重写、替换或补写专业章节正文；只能接受章节，或给原章节分析师具体退修指令。"
                "你可以写执行判断、综合建议、解读边界、章节顺序和章节间过渡，但每个综合陈述必须填写已有 ArgumentUnit.argument_id 作为 claim_ids。"
                "不得提出专业章节中不存在的新判断；如确需新判断，退回对应章节补写 ArgumentUnit。跨章冲突必须明确裁决，不能静默合并。"
                + ("这是退修后的最终审校，必须全部 accepted 并 publication_decision=ready。" if final_pass else "这是首次审校，可要求 revise。")
            ),
            user_payload={
                "project_analysis_blueprint": blueprint.model_dump(mode="json"),
                "analyst_chapters": [item.model_dump(mode="json") for item in chapters],
                "evidence_nodes": evidence_nodes,
                "diagnostics": diagnostics,
            },
            phase="spatial-editorial-review-final" if final_pass else "spatial-editorial-review",
            title="主分析师最终审校" if final_pass else "主分析师审校专业章节",
            reasoning_id="spatial-main-editorial-final" if final_pass else "spatial-main-editorial",
            validator=validate,
        )

