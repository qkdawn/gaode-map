class EvidenceAccess(BaseModel):
    model_config = ConfigDict(extra="forbid")

    primary_refs: list[str] = Field(default_factory=list)
    shared_refs: list[str] = Field(default_factory=list)
    gap_refs: list[str] = Field(default_factory=list)
    visual_refs: list[str] = Field(default_factory=list)
    forbidden_refs: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _validate_access(self):
        groups = {
            "primary": set(self.primary_refs),
            "shared": set(self.shared_refs),
            "gap": set(self.gap_refs),
            "visual": set(self.visual_refs),
            "forbidden": set(self.forbidden_refs),
        }
        labels = list(groups)
        for index, label in enumerate(labels):
            for other in labels[index + 1 :]:
                overlap = groups[label] & groups[other]
                if overlap:
                    raise ValueError(
                        f"EvidenceAccess reference categories must be disjoint: {label}/{other}: {sorted(overlap)}"
                    )
        return self


