# Public semantic keys are deliberately stable. Metric ids, adapters, parameters,
# and execution order remain implementation details of the evidence engine.
EVIDENCE_CAPABILITY_REGISTRY: dict[str, dict[str, str]] = {
    "project_constraints": {"kind": "document", "description": "Extract binding project constraints."},
    "facility_supply_structure": {"kind": "metric", "description": "Measure facility supply and category structure."},
    "spatial_concentration": {"kind": "spatial", "description": "Measure concentration, clustering, or dispersion."},
    "network_access_structure": {"kind": "spatial", "description": "Evaluate road-network accessibility and reach."},
    "entrance_comparison": {"kind": "comparison", "description": "Compare declared entrances using consistent evidence."},
    "population_context": {"kind": "metric", "description": "Describe population context without inferring visits."},
    "night_activity_context": {"kind": "metric", "description": "Describe nightlight intensity as a contextual proxy."},
    "temporal_change": {"kind": "comparison", "description": "Compare like-for-like observations over time."},
}
EVIDENCE_CAPABILITY_REGISTRY_HASH = _digest(EVIDENCE_CAPABILITY_REGISTRY)


def resolve_evidence_capability(capability: str) -> dict[str, str]:
    """Resolve a public capability without exposing its execution implementation."""

    try:
        return dict(EVIDENCE_CAPABILITY_REGISTRY[capability])
    except KeyError as exc:
        raise ValueError(f"unknown evidence_capability: {capability}") from exc


class BlueprintEvidenceRequirement(BaseModel):
    model_config = ConfigDict(extra="forbid")

    requirement_id: str
    kind: Literal["document", "metric", "spatial", "comparison", "gap"]
    objective: str
    evidence_capability: str = ""
    required_sources: list[str] = Field(default_factory=list)
    failure_effect: str

    @model_validator(mode="after")
    def _validate_requirement(self):
        if any(not value.strip() for value in (self.requirement_id, self.objective, self.failure_effect)):
            raise ValueError("evidence requirement requires id, objective, and failure_effect")
        if self.kind in {"metric", "spatial", "comparison"}:
            if not self.evidence_capability.strip():
                raise ValueError(f"{self.kind} evidence requirement requires evidence_capability")
            capability = resolve_evidence_capability(self.evidence_capability)
            if capability["kind"] != self.kind:
                raise ValueError(
                    f"evidence_capability {self.evidence_capability} is registered for {capability['kind']}, not {self.kind}"
                )
        elif self.evidence_capability:
            capability = resolve_evidence_capability(self.evidence_capability)
            if self.kind == "document" and capability["kind"] != "document":
                raise ValueError("document evidence must use a document capability")
        if len(self.required_sources) != len(set(self.required_sources)):
            raise ValueError("evidence requirement required_sources must be unique")
        return self


