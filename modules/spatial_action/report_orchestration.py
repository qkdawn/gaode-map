EvidenceAttemptKind = Literal["metric", "document", "spatial", "comparison", "gap"]
EvidenceExecutionStatus = Literal["succeeded", "blocked", "failed", "not_applicable", "registered_gap"]


class EvidenceAttempt(BaseModel):
    model_config = ConfigDict(extra="forbid")

    attempt_id: str
    plan_ref_id: str
    decision_question_id: str
    kind: EvidenceAttemptKind
    execution_status: EvidenceExecutionStatus
    source_ids: list[str] = Field(default_factory=list)
    evidence_node_ids: list[str] = Field(default_factory=list)
    reason: str = ""

    @model_validator(mode="after")
    def _validate_attempt(self):
        if self.execution_status == "succeeded" and not self.evidence_node_ids:
            raise ValueError("succeeded EvidenceAttempt requires EvidenceNodes")
        if self.execution_status != "succeeded" and self.evidence_node_ids:
            raise ValueError("non-succeeded EvidenceAttempt cannot reference EvidenceNodes")
        if self.kind == "gap" and self.execution_status != "registered_gap":
            raise ValueError("gap EvidenceAttempt must use registered_gap")
        if self.kind != "gap" and self.execution_status == "registered_gap":
            raise ValueError("registered_gap is reserved for gap EvidencePlan items")
        if self.execution_status != "succeeded" and not self.reason.strip():
            raise ValueError("non-succeeded EvidenceAttempt requires a reason")
        return self


