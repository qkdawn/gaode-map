def _digest(value: Any) -> str:
    raw = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), default=str)
    return f"sha256:{hashlib.sha256(raw.encode('utf-8')).hexdigest()}"


class OrchestrationError(RuntimeError):
    """A report cannot be safely generated by the configured LLM workflow."""

    def __init__(
        self,
        message: str,
        *,
        run_status: Literal["waiting_for_user", "chapter_failed", "publication_blocked", "system_failed"] = "system_failed",
        partial_artifacts: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(message)
        self.run_status = run_status
        self.partial_artifacts = partial_artifacts or {}


class ExcludedTopic(BaseModel):
    model_config = ConfigDict(extra="forbid")

    topic: str
    reason: str

    @model_validator(mode="after")
    def _validate_content(self):
        if not self.topic.strip() or not self.reason.strip():
            raise ValueError("excluded topic requires a topic and reason")
        return self


class EvidencePlanItem(BaseModel):
    model_config = ConfigDict(extra="forbid")

    plan_id: str
    objective: str
    required_source_ids: list[str] = Field(default_factory=list)
    method: str
    decision_use: str
    failure_effect: str

    @model_validator(mode="after")
    def _validate_content(self):
        required = (self.plan_id, self.objective, self.method, self.decision_use, self.failure_effect)
        if any(not item.strip() for item in required):
            raise ValueError("EvidencePlanItem requires complete non-empty content")
        if len(self.required_source_ids) != len(set(self.required_source_ids)):
            raise ValueError("EvidencePlanItem required_source_ids must be unique")
        return self


class EvidencePlan(BaseModel):
    model_config = ConfigDict(extra="forbid")

    decision_question_id: str
    metric_plan_entry_ids: list[str] = Field(default_factory=list)
    document_evidence: list[EvidencePlanItem] = Field(default_factory=list)
    spatial_evidence: list[EvidencePlanItem] = Field(default_factory=list)
    comparisons: list[EvidencePlanItem] = Field(default_factory=list)
    evidence_gap_plans: list[EvidencePlanItem] = Field(default_factory=list)

    @model_validator(mode="after")
    def _validate_evidence_plan(self):
        if not any(
            (
                self.metric_plan_entry_ids,
                self.document_evidence,
                self.spatial_evidence,
                self.comparisons,
                self.evidence_gap_plans,
            )
        ):
            raise ValueError("every DecisionQuestion requires a non-empty EvidencePlan")
        item_ids = [
            item.plan_id
            for group in (
                self.document_evidence,
                self.spatial_evidence,
                self.comparisons,
                self.evidence_gap_plans,
            )
            for item in group
        ]
        if len(item_ids) != len(set(item_ids)):
            raise ValueError("EvidencePlan non-metric plan ids must be unique within a question")
        for item in [*self.document_evidence, *self.spatial_evidence, *self.comparisons]:
            if not item.required_source_ids:
                raise ValueError("positive non-metric EvidencePlan items require required_source_ids")
        return self


