class EditorialReview(EditorialReviewDraft):
    accepted_claims: list[AcceptedClaim] = Field(default_factory=list)
    review_hash: str

    @classmethod
    def model_validate(cls, obj: Any, *args: Any, **kwargs: Any):
        if isinstance(obj, dict) and obj.get("schema_version") == "2.0":
            return LegacyEditorialReview.model_validate(obj, *args, **kwargs)
        return super().model_validate(obj, *args, **kwargs)

    @model_validator(mode="after")
    def _validate_review(self):
        version_ids = [item.chapter_version_id for item in self.chapter_decisions]
        if len(version_ids) != len(set(version_ids)):
            raise ValueError("EditorialReview decisions must be unique by chapter version")
        latest: dict[str, tuple[int, V3ChapterEditorialDecision]] = {}
        history: dict[str, dict[int, V3ChapterEditorialDecision]] = {}
        for item in self.chapter_decisions:
            match = re.search(r"(?:^|[:._-])v(\d+)$", item.chapter_version_id, re.IGNORECASE)
            if not match or int(match.group(1)) not in {1, 2}:
                raise ValueError("editorial decisions must reference chapter v1 or v2")
            revision = int(match.group(1))
            history.setdefault(item.chapter_id, {})[revision] = item
            current = latest.get(item.chapter_id)
            if current is None or revision > current[0]:
                latest[item.chapter_id] = (revision, item)
        for chapter_id, decisions in history.items():
            if set(decisions) not in ({1}, {1, 2}):
                raise ValueError(f"EditorialReview must preserve contiguous review history for {chapter_id}")
            if 2 in decisions and decisions[1].status != "revise":
                raise ValueError("a v2 decision is only valid after a v1 revision request")
            if 2 in decisions and decisions[2].status == "revise":
                raise ValueError("v2 is the final allowed repair and cannot request another revision")
        if self.publication_decision == "ready" and any(item.status != "accepted" for _, item in latest.values()):
            raise ValueError("ready EditorialReview requires every latest chapter version to be accepted")
        if self.publication_decision == "ready" and not self.accepted_claims:
            raise ValueError("ready EditorialReview requires system-generated accepted claims")
        claim_ids = [item.claim_id for item in self.accepted_claims]
        if len(claim_ids) != len(set(claim_ids)):
            raise ValueError("EditorialReview accepted claim ids must be unique")
        payload = self.model_dump(mode="json", exclude={"review_hash"})
        if self.review_hash != _digest(payload):
            raise ValueError("EditorialReview review_hash does not match its content")
        return self


