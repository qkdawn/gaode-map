def build_editorial_review(
    draft: EditorialReviewDraft,
    chapters: list[ChapterPackage],
) -> EditorialReview:
    """Generate accepted claims deterministically from accepted chapter versions."""

    by_version = {item.chapter_version_id: item for item in chapters}
    accepted: list[AcceptedClaim] = []
    argument_by_id: dict[str, tuple[ChapterPackage, ArgumentUnit]] = {}
    for chapter in chapters:
        for subsection in chapter.subsections:
            for argument in subsection.argument_units:
                argument_by_id[argument.argument_id] = (chapter, argument)
    accepted_versions = {
        item.chapter_version_id for item in draft.chapter_decisions if item.status == "accepted"
    }
    unknown = accepted_versions - set(by_version)
    if unknown:
        raise ValueError(f"editorial decisions reference unknown chapter versions: {sorted(unknown)}")
    for version_id in sorted(accepted_versions):
        chapter = by_version[version_id]
        for subsection in chapter.subsections:
            for argument in subsection.argument_units:
                accepted.append(AcceptedClaim(
                    claim_id=argument.argument_id,
                    source_type="argument_unit",
                    source_chapter_id=chapter.chapter_id,
                    argument_id=argument.argument_id,
                    claim=argument.claim,
                    evidence_refs=argument.evidence_refs,
                    evidence_gap_refs=argument.evidence_gap_refs,
                    evidence_state=argument.evidence_state,
                    baseline=argument.baseline,
                    scope=",".join(subsection.decision_question_ids),
                ))
    accepted_argument_ids = {item.argument_id for item in accepted if item.source_type == "argument_unit"}
    state_rank = {"measured": 0, "proxy": 1, "inference": 2, "recommendation": 3, "experimental_assumption": 4}
    for conflict in draft.conflicts:
        if not set(conflict.claim_ids) <= accepted_argument_ids:
            raise ValueError(f"conflict {conflict.conflict_id} may only cite accepted chapter claims")
        source_arguments = [argument_by_id[item][1] for item in conflict.claim_ids if item in argument_by_id]
        if len(source_arguments) != len(conflict.claim_ids):
            raise ValueError(f"conflict {conflict.conflict_id} references unknown claims")
        weakest = max(source_arguments, key=lambda item: state_rank[item.evidence_state]).evidence_state
        accepted.append(AcceptedClaim(
            claim_id=conflict.conflict_id,
            source_type="conflict_ruling",
            source_conflict_id=conflict.conflict_id,
            claim=conflict.resolution,
            evidence_refs=sorted({ref for item in source_arguments for ref in item.evidence_refs}),
            evidence_gap_refs=sorted({ref for item in source_arguments for ref in item.evidence_gap_refs}),
            evidence_state=weakest,
            baseline="conflicting accepted chapter claims",
            scope=",".join(conflict.chapter_ids),
        ))
    payload = draft.model_dump(mode="json") | {"accepted_claims": [item.model_dump(mode="json") for item in accepted]}
    payload["review_hash"] = _digest(payload)
    return EditorialReview.model_validate(payload)


def validate_chapter_package(
    package: ChapterPackage,
    assignment: V3ChapterAssignment,
    snapshot: EvidenceSnapshot,
    *,
    expected_revision: Literal[1, 2],
) -> None:
    """Enforce a specialist's complete assignment and evidence boundary."""

    if package.run_id != snapshot.run_id:
        raise ValueError("ChapterPackage run_id does not match EvidenceSnapshot")
    if package.chapter_id != assignment.chapter_id or package.analyst_role != assignment.role:
        raise ValueError("ChapterPackage identity or analyst role does not match assignment")
    if package.assignment_hash != assignment.assignment_hash or package.evidence_snapshot_hash != snapshot.snapshot_hash:
        raise ValueError("ChapterPackage does not bind its assignment and evidence snapshot")
    if not re.search(rf"(?:^|[:._-])v{expected_revision}$", package.chapter_version_id, re.IGNORECASE):
        raise ValueError(f"ChapterPackage must use revision v{expected_revision}")
    if set(package.decision_question_ids) != set(assignment.question_ids):
        raise ValueError("ChapterPackage must cover exactly its assigned questions")
    expected_subsections = {item.subsection_id for item in assignment.subsection_tasks}
    actual_subsections = {item.subsection_id for item in package.subsections}
    if actual_subsections != expected_subsections:
        raise ValueError("ChapterPackage must return every assigned subsection exactly once")
    task_by_id = {item.subsection_id: item for item in assignment.subsection_tasks}
    for subsection in package.subsections:
        if set(subsection.decision_question_ids) != set(task_by_id[subsection.subsection_id].question_ids):
            raise ValueError("ChapterPackage subsection question coverage differs from assignment")
        actual_argument_ids = {item.argument_id for item in subsection.argument_units}
        if not set(task_by_id[subsection.subsection_id].required_argument_units) <= actual_argument_ids:
            raise ValueError("ChapterPackage omitted required ArgumentUnits")
    access = assignment.evidence_access
    allowed_evidence = set(access.primary + access.shared)
    allowed_gaps = set(access.gaps)
    allowed_visuals = set(access.visuals)
    forbidden = set(access.forbidden)
    evidence_refs = {
        ref for subsection in package.subsections for ref in subsection.evidence_ids
    } | {
        ref for subsection in package.subsections for argument in subsection.argument_units for ref in argument.evidence_refs
    } | {
        ref for item in package.finding_packets for ref in item.evidence_ids
    } | {
        ref for subsection in package.subsections for block in subsection.structured_blocks for ref in block.evidence_ids
    }
    gap_refs = {
        ref for subsection in package.subsections for ref in subsection.evidence_gap_ids
    } | {
        ref for subsection in package.subsections for argument in subsection.argument_units for ref in argument.evidence_gap_refs
    } | {
        ref for subsection in package.subsections for block in subsection.structured_blocks for ref in block.evidence_gap_ids
    } | {item.gap_id for item in package.evidence_gaps}
    visual_refs = {ref.visual_id for subsection in package.subsections for ref in subsection.visual_refs}
    if not evidence_refs <= allowed_evidence or evidence_refs & forbidden:
        raise ValueError("ChapterPackage cites evidence outside its whitelist")
    if not gap_refs <= allowed_gaps or gap_refs & forbidden:
        raise ValueError("ChapterPackage cites gaps outside its whitelist")
    if visual_refs != allowed_visuals or visual_refs & forbidden:
        raise ValueError("ChapterPackage must place and interpret every assigned visual")
    snapshot_evidence = {item.evidence_id for item in snapshot.evidence}
    snapshot_gaps = {item.gap_id for item in snapshot.gaps}
    snapshot_visuals = {item.visual_id for item in snapshot.visuals}
    if not evidence_refs <= snapshot_evidence or not gap_refs <= snapshot_gaps or not visual_refs <= snapshot_visuals:
        raise ValueError("ChapterPackage references an object absent from EvidenceSnapshot")
    evidence_by_id = {item.evidence_id: item for item in snapshot.evidence}
    for subsection in package.subsections:
        for argument in subsection.argument_units:
            if argument.evidence_state in {"measured", "proxy"} and not argument.evidence_result_refs:
                raise ValueError("measured or proxy ArgumentUnit requires evidence result field lineage")
            for result_ref in argument.evidence_result_refs:
                if result_ref.evidence_id not in allowed_evidence:
                    raise ValueError("ArgumentUnit result lineage cites evidence outside its whitelist")
                value: Any = evidence_by_id[result_ref.evidence_id].result
                for component in result_ref.field_path.split("."):
                    if not isinstance(value, dict) or component not in value:
                        raise ValueError("ArgumentUnit result lineage references an unknown result field")
                    value = value[component]
    if package.content_hash != _digest(package.model_dump(mode="json", exclude={"content_hash"})):
        raise ValueError("ChapterPackage content_hash does not match its content")


def validate_report_assembly(
    assembly: ReportAssembly,
    review: EditorialReview,
    chapters: list[ChapterPackage],
) -> None:
    """Ensure main-analyst synthesis is limited to accepted claims and chapters."""

    if assembly.run_id != review.run_id or review.publication_decision != "ready":
        raise ValueError("ReportAssembly requires a ready EditorialReview from the same run")
    accepted_claim_ids = {item.claim_id for item in review.accepted_claims}
    used_claim_ids = set(assembly.executive_summary.claim_ids)
    used_claim_ids.update(
        claim_id for statement in assembly.integrated_recommendations for claim_id in statement.claim_ids
    )
    used_claim_ids.update(claim_id for transition in assembly.transitions for claim_id in transition.claim_ids)
    if not used_claim_ids <= accepted_claim_ids:
        raise ValueError("ReportAssembly synthesis may only cite accepted claim ids")
    conflict_ids = {item.conflict_id for item in review.conflicts}
    if not set(assembly.conflict_references) <= conflict_ids:
        raise ValueError("ReportAssembly references unknown editorial conflicts")
    chapter_by_version = {item.chapter_version_id: item for item in chapters}
    latest_accepted_with_revision: dict[str, tuple[int, str]] = {}
    for item in review.chapter_decisions:
        if item.status != "accepted":
            continue
        match = re.search(r"(?:^|[:._-])v(\d+)$", item.chapter_version_id, re.IGNORECASE)
        revision = int(match.group(1)) if match else 0
        current = latest_accepted_with_revision.get(item.chapter_id)
        if current is None or revision > current[0]:
            latest_accepted_with_revision[item.chapter_id] = (revision, item.chapter_version_id)
    latest_accepted = {chapter_id: value[1] for chapter_id, value in latest_accepted_with_revision.items()}
    for ref in assembly.accepted_chapters:
        chapter = chapter_by_version.get(ref.chapter_version_id)
        if chapter is None or chapter.chapter_id != ref.chapter_id or chapter.content_hash != ref.content_hash:
            raise ValueError("ReportAssembly references an unknown or hash-mismatched chapter")
        if latest_accepted.get(ref.chapter_id) != ref.chapter_version_id:
            raise ValueError("ReportAssembly may only use editorially accepted chapter versions")


def validate_v3_contracts(
    blueprint: AnalysisBlueprint,
    snapshot: EvidenceSnapshot,
    assignments: ChapterAssignments,
) -> None:
    """Validate cross-object coverage while keeping individual public APIs small."""

    if snapshot.blueprint_hash != blueprint.lock.content_hash:
        raise ValueError("EvidenceSnapshot does not bind the locked AnalysisBlueprint")
    if assignments.blueprint_hash != blueprint.lock.content_hash or assignments.evidence_snapshot_hash != snapshot.snapshot_hash:
        raise ValueError("ChapterAssignments do not bind the locked blueprint and evidence snapshot")
    question_ids = {item.question_id for item in blueprint.decision_questions}
    if set(snapshot.question_readiness) != question_ids:
        raise ValueError("EvidenceSnapshot readiness must cover every decision question")
    assignment_questions = {question for item in assignments.chapters for question in item.question_ids}
    if assignment_questions != question_ids:
        raise ValueError("ChapterAssignments must cover every decision question")
    requirement_ids = {
        item.requirement_id for group in blueprint.evidence_requirements for item in group.items
    }
    attempt_requirements = [item.requirement_id for item in snapshot.execution_lineage.attempts]
    if len(attempt_requirements) != len(set(attempt_requirements)) or set(attempt_requirements) != requirement_ids:
        raise ValueError("every evidence requirement requires exactly one terminal lineage attempt")
    requirement_question = {
        item.requirement_id: group.question_id
        for group in blueprint.evidence_requirements for item in group.items
    }
    for evidence in snapshot.evidence:
        if evidence.requirement_id not in requirement_ids:
            raise ValueError("EvidenceSnapshot evidence references an unknown blueprint requirement")
        if requirement_question[evidence.requirement_id] not in set(evidence.question_ids):
            raise ValueError("EvidenceSnapshot evidence does not cover its requirement question")
    for gap in snapshot.gaps:
        if gap.requirement_id not in requirement_ids or gap.question_id != requirement_question[gap.requirement_id]:
            raise ValueError("EvidenceSnapshot gap does not match its blueprint requirement")
    evidence_ids = {item.evidence_id for item in snapshot.evidence}
    gap_ids = {item.gap_id for item in snapshot.gaps}
    visual_ids = {item.visual_id for item in snapshot.visuals}
    for assignment in assignments.chapters:
        access = assignment.evidence_access
        if not set(access.primary + access.shared) <= evidence_ids:
            raise ValueError("ChapterAssignments reference unknown evidence")
        if not set(access.gaps) <= gap_ids or not set(access.visuals) <= visual_ids:
            raise ValueError("ChapterAssignments reference unknown gaps or visuals")


