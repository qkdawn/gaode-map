        "请基于提供的结构化证据，输出最终 JSON 结果。"
        "必须只输出 JSON。"
        "JSON 结构固定为："
        "{\"answer\":\"...\"}"
        "规则："
        "1. answer 必须先直接回答用户问题，不能先铺垫方法论或复述任务；"
